  /**
   * Admin: Upload gift card design image to Supabase Storage
   */
  async uploadDesignImage(adminId: string, file: any): Promise<{
    url: string;
    fileData: {
      name: string;
      size: number;
      type: string;
      mimeType: string;
    };
  }> {
    const BUCKET_NAME = 'gift-card-designs'; // Create this bucket in Supabase Storage
    const MAX_FILE_SIZE = 10 * 1024 * 1024; // 10MB

    if (file.size > MAX_FILE_SIZE) {
      throw new BadRequestException('File too large. Maximum size is 10MB');
    }

    if (!file.mimetype || !file.mimetype.startsWith('image/')) {
      throw new BadRequestException('Only image files are allowed for gift card designs');
    }

    try {
      // Generate unique filename
      const fileExtension = file.originalname ? file.originalname.split('.').pop() : 'png';
      const uniqueFileName = `${adminId}/${Date.now()}_${Math.random().toString(36).substring(2)}.${fileExtension}`;

      // Upload file to Supabase Storage
      const { data: uploadData, error: uploadError } = await this.supabase.storage
        .from(BUCKET_NAME)
        .upload(uniqueFileName, file.buffer, {
          contentType: file.mimetype,
          upsert: false,
        });

      if (uploadError) {
        this.logger.error('Gift card design upload failed:', uploadError);
        throw new BadRequestException(`Upload failed: ${uploadError.message}`);
      }

      // Get public URL
      const { data: urlData } = this.supabase.storage
        .from(BUCKET_NAME)
        .getPublicUrl(uniqueFileName);

      return {
        url: urlData.publicUrl,
        fileData: {
          name: file.originalname,
          size: file.size,
          type: 'image',
          mimeType: file.mimetype,
        },
      };
    } catch (error) {
      this.logger.error('Gift card design upload error:', error);
      throw error;
    }
  }

