  /**
   * Admin: Get gift card statistics
   */
  async getGiftCardStats() {
    const { data: cards, error } = await this.supabase
      .from('gift_cards')
      .select('status, initial_balance, current_balance, created_at');
    
    if (error) {
      throw new BadRequestException(`Failed to fetch statistics: ${error.message}`);
    }
    
    const stats = {
      total_issued: cards.length,
      total_redeemed: cards.filter(c => c.status === 'redeemed').length,
      total_active: cards.filter(c => c.status === 'active' || c.status === 'claimed').length,
      total_expired: cards.filter(c => c.status === 'expired').length,
      total_blocked: cards.filter(c => c.status === 'blocked').length,
      total_value_issued: cards.reduce((sum, c) => sum + Number(c.initial_balance), 0),
      total_value_redeemed: cards.filter(c => c.status === 'redeemed').reduce((sum, c) => sum + (Number(c.initial_balance) - Number(c.current_balance)), 0),
      total_value_active: cards.filter(c => c.status === 'active' || c.status === 'claimed').reduce((sum, c) => sum + Number(c.current_balance), 0),
      redemption_rate: 0,
      breakage_rate: 0,
      period_revenue: 0
    };
    
    // Calculate rates
    if (stats.total_issued > 0) {
      stats.redemption_rate = (stats.total_redeemed / stats.total_issued) * 100;
      stats.breakage_rate = (stats.total_expired / stats.total_issued) * 100;
    }
    
    // Calculate period revenue (last 30 days)
    const thirtyDaysAgo = new Date();
    thirtyDaysAgo.setDate(thirtyDaysAgo.getDate() - 30);
    
    const recentCards = cards.filter(c => new Date(c.created_at) >= thirtyDaysAgo);
    stats.period_revenue = recentCards.reduce((sum, c) => sum + Number(c.initial_balance), 0);
    
    return stats;
  }

  /**
   * Admin: Get gift card analytics
   */
  async getGiftCardAnalytics(period: string = '30d') {
    const days = period === '7d' ? 7 : period === '90d' ? 90 : 30;
    const startDate = new Date();
    startDate.setDate(startDate.getDate() - days);
    
    const { data: cards, error } = await this.supabase
      .from('gift_cards')
      .select('status, initial_balance, current_balance, created_at, expires_at')
      .gte('created_at', startDate.toISOString());
    
    if (error) {
      throw new BadRequestException(`Failed to fetch analytics: ${error.message}`);
    }
    
    // Group by day
    const dailyData = {};
    cards.forEach(card => {
      const day = new Date(card.created_at).toISOString().split('T')[0];
      if (!dailyData[day]) {
        dailyData[day] = { issued: 0, redeemed: 0, value: 0 };
      }
      dailyData[day].issued++;
      dailyData[day].value += Number(card.initial_balance);
      if (card.status === 'redeemed') {
        dailyData[day].redeemed++;
      }
    });
    
    return {
      period,
      days,
      dailyData,
      totalCards: cards.length,
      totalValue: cards.reduce((sum, c) => sum + Number(c.initial_balance), 0),
      redemptionRate: cards.length > 0 ? (cards.filter(c => c.status === 'redeemed').length / cards.length) * 100 : 0
    };
  }

