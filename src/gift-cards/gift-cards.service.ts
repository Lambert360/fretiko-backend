  async refundGiftCard(orderId: string, amount: number, reason: string, orderGroupId?: string): Promise<void> {
    // Find the gift card transaction for this order. For orders that are part of a
    // multi-vendor group, only the first order in the group is directly linked via
    // order_id (the gift card is applied once for the whole group) - fall back to
    // looking the transaction up by order_group_id so any suborder in the group can
    // trigger a correctly-scoped partial refund.
    let { data: transaction } = await this.supabase
      .from('gift_card_transactions')
      .select('*')
      .eq('order_id', orderId)
      .eq('transaction_type', 'redeem')
      .single();

    if (!transaction && orderGroupId) {
      const { data: groupTransaction } = await this.supabase
        .from('gift_card_transactions')
        .select('*')
        .eq('transaction_type', 'redeem')
        .eq('metadata->>order_group_id', orderGroupId)
        .single();
      transaction = groupTransaction;
    }
    
    if (!transaction) {
      throw new NotFoundException('Gift card transaction not found for this order');
    }
    
    // ✅ ATOMIC FIX: All wallet movements, gift card balance/status update,
    // and audit log are now handled by revert_gift_card_redemption_atomic().
    const { data: revertResult, error: revertRpcError } = await this.supabase.rpc(
      'revert_gift_card_redemption_atomic',
      {
        p_transaction_id: transaction.id,
        p_amount: amount,
        p_reason: reason,
        p_admin_gift_user_id: this.adminGiftWalletId,
        p_order_id: orderId,
      }
    );

    if (revertRpcError) {
      this.logger.error('revert_gift_card_redemption_atomic RPC error:', revertRpcError);
      throw new Error(`Gift card refund failed: ${revertRpcError.message}`);
    }

    if (!revertResult || !revertResult.success) {
      throw new Error(`Gift card refund failed: ${revertResult?.error || 'Unknown error'}`);
    }
  }
  
